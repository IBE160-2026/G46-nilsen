const fs = require('fs');
const assert = require('assert');
const html = fs.readFileSync('index.html','utf8');
const debug = fs.readFileSync('login-debug.js','utf8');
const server = fs.readFileSync('server.js','utf8');
assert(html.includes('login-debug-panel'));
assert(html.includes('login-debug.js?v=19.11.4'));
assert(debug.includes('/api/auth/login'));
assert(debug.includes('/api/auth/me'));
assert(debug.includes('stopImmediatePropagation'));
assert(server.includes('/api/auth/diagnostic'));
assert(server.includes('X-Debug-Request-Id'));
console.log('v19.11.4-debug diagnostics present: OK');
