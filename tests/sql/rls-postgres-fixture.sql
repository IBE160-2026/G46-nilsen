-- Disposable PostgreSQL 17 fixture for actual repository V20-8 RLS migration.
-- This is NOT a full Supabase Auth/PostgREST installation, and must never run on production.
\set ON_ERROR_STOP on
create role anon nologin;
create role authenticated nologin;
create role service_role nologin;

create schema auth;
create function auth.uid() returns uuid
  language sql stable
  as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth to anon,authenticated;
grant execute on function auth.uid() to anon,authenticated;
grant usage on schema public to anon,authenticated,service_role;

-- Match the six production conversation columns including bigint ID.
create table public.conversations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid,
  title text,
  content text,
  updated_at timestamptz default now()
);
alter table public.conversations enable row level security;
grant select,insert,update,delete on public.conversations to authenticated;
grant usage,select on sequence public.conversations_id_seq to authenticated;

